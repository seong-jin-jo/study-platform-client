export type ScenarioStatus = 'ready' | 'blocked' | 'partial';

export interface ScenarioStep {
  /** 어느 화면/URL에서 하는가 (예: "/admin/sales-management/쿠폰 관리") */
  where: string;
  /** 무엇을 누르거나 입력하는가 */
  action: string;
  /** 입력값 예시 (있으면) */
  input?: string;
  /** 무엇이 보이면 통과인가 (합격 기준) */
  expect: string;
  /** 이게 보이면 실패 (있으면) */
  fail?: string;
}

export interface Scenario {
  id: string;
  /** 한 줄 제목 */
  title: string;
  /** 묶음(필터용): 쿠폰 / 위키 / 완주 등 */
  feature: string;
  /** 누가 하는 여정인가 */
  persona: string;
  /** 지금 실행 가능 여부 */
  status: ScenarioStatus;
  /** blocked/partial 사유 (왜 아직 못 누르나) */
  statusReason?: string;
  /** 시작 전 준비물 */
  preconditions: string[];
  steps: ScenarioStep[];
}

